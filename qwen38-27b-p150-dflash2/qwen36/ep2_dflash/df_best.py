def apply():
    name = os.environ.get("QWEN38_BEST", "")
    if not name or os.environ.get("_QWEN38_BEST_APPLIED") == name:
        return
    if name not in PROFILES:
        raise ValueError(f"QWEN38_BEST={name!r}: unknown (have {sorted(PROFILES)})")
    s = PROFILES[name]
    over = {k: os.environ[k] for k in s if k in os.environ and os.environ[k] != s[k]}
    for k, v in s.items():
        os.environ.setdefault(k, v)
    os.environ["_QWEN38_BEST_APPLIED"] = name
    print(f"QWEN38_BEST={name}: {len(s)} switches, overridden by explicit env: {over or 'none'}", flush=True)


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "--env" and sys.argv[2] in PROFILES:
        for k, v in PROFILES[sys.argv[2]].items():
            print(f"{k}={v}")
    else:
        sys.exit("usage: df_best.py --env 2card|1card")
